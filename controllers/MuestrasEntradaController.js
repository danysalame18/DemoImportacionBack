const { MuestrasEntrada } = require('../models')

module.exports = { 
    findAll: (req, res)=>{
        MuestrasEntrada.find()
        .populate('areas')
        .populate('user')
        .populate('clientes')
            .then((respDB)=> res.status(200).json(respDB))
            .catch((err)=> console.log(err))
    },
    findOne: (req, res)=>{
        const { id } = req.params
        MuestrasEntrada.findById(id)
        .populate('areas')
        .populate('user')
        .populate('clientes')
            .then((respDB)=> res.status(200).json(respDB))
            .catch((err)=> console.log(err))
    },
    create: (req, res)=>{
        const { body } = req
        const newMuestras = new MuestrasEntrada(body)
        const traspaso = newMuestras.save()
            .then((respDB)=> res.status(201).json(respDB))
            .catch((err)=> console.log(err))
    },
    delete: (req, res)=>{
        MuestrasEntrada.findByIdAndDelete(req.params.id)
            .then((resDB)=> res.status(204).json(resDB))
            .catch((err)=> res.status(400).json(err))
    },
    edit: (req, res)=>{
        const { body } = req
        MuestrasEntrada.findByIdAndUpdate(req.params.id, body, { new: true})
        .then((resDB)=> res.status(201).json(resDB))
        .catch((err)=> res.status(400).json(err))
    }
}